// Writes vendor/fonts.css: Inter + JetBrains Mono (variable, latin) inlined as base64 so the UI
// stays fully offline and server4.js's static handler (js/css only) needs no font route.
// Run after `npm i` if the @fontsource-variable packages change: `npm run build:fonts`.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const faces = [
    ['Inter Variable', '@fontsource-variable/inter/files/inter-latin-wght-normal.woff2', '100 900'],
    ['JetBrains Mono Variable', '@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2', '100 800'],
];
const css = faces.map(([family, file, weight]) => {
    const b64 = fs.readFileSync(path.join(root, 'node_modules', file)).toString('base64');
    return `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${weight};src:url(data:font/woff2;base64,${b64}) format('woff2');}`;
}).join('\n');
fs.writeFileSync(path.join(root, 'vendor', 'fonts.css'), `/* generated by tools/build-fonts.js -- do not edit */\n${css}\n`);
console.log('vendor/fonts.css', css.length, 'bytes');
